"""D4: render samples/ground-truth.md from the generated case files (never edited by hand).

    python samples/generator/ground_truth_doc.py          # rewrite samples/ground-truth.md
    python samples/validate.py                            # fails if the committed file is stale
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
    __package__ = "samples.generator"

from .common import SAMPLES_DIR


def _esc(s) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def _load(p: Path):
    return json.loads(p.read_text(encoding="utf-8"))


def _case_table(case_dir: Path) -> str:
    case = _load(case_dir / "case.json")
    ef = _load(case_dir / "expected_findings.json")["findings"]
    nf = _load(case_dir / "expected_non_findings.json")["non_findings"]
    docs = "<br>".join(f"`{d['file']}` ({d['role']}, {d['variant']})" for d in case["documents"])
    people = "; ".join(f"{p['role']} {p['full_name']} ({p['person_id']})" for p in case["persons"])
    intended = []
    for g in case["tamper_ground_truth"]:
        intended.append(f"**Edit {g['id']}** `{g['type']}` in `{g['doc_id']}`"
                        + (f" field `{g['field']}`" if g.get("field") else "") + f": {g['description']}")
    legit = [n for n in nf if "legitimateDifferenceId" in n]
    if legit:
        intended.append("**Legitimate differences (must not be reported):** "
                        + "; ".join(f"{n['legitimateDifferenceId']} {n['description']}" for n in legit))
    for n in nf:
        if "legitimateDifferenceId" not in n and n["fields"]:
            intended.append(f"**{n['nonFindingId']}:** {n['description']}")
    if not case["tamper_ground_truth"] and case["pattern"] == "S8":
        intended.append("Genuine content only recompressed as JPEG; nothing was edited.")
    findings = [f"**{f['expectedId']}** `{f['type']}` ({f['category']}, {f['severity']}, {f['observationStatus']}"
                + (f", {f['scoring']}" if "scoring" in f else "") + f") on {', '.join(f'`{d}`' for d in f['documents'])}: "
                + f["notes"] for f in ef] or ["None. Any finding on this case is a false positive."]
    forensic = [n for n in nf if n["forbiddenTypes"] != ["*"] and n["fields"] == []]
    non = [f"**{n['nonFindingId']}** {n['description']} (forbidden: {', '.join(n['forbiddenTypes'])})"
           for n in nf if n["forbiddenTypes"] == ["*"]]
    if forensic:
        non.append(f"No forensic finding ({', '.join(forensic[0]['forbiddenTypes'])}) on: "
                   + ", ".join(f"`{n['documents'][0]}`" for n in forensic) + f". {forensic[0]['reason']}")
    other = [f"**{n['nonFindingId']}** {n['description']} (forbidden: {', '.join(n['forbiddenTypes'])})"
             for n in nf if n["forbiddenTypes"] not in (["*"],) and n["fields"]]
    non += other
    rows = [("People", people), ("Documents", docs), ("Intended edit or legitimate difference", "<br>".join(intended) or "None"),
            ("Expected findings", "<br>".join(findings)), ("Expected non-findings", "<br>".join(non))]
    head = f"### {case['caseId']}: {case['patternName']} ({case['split']})\n\n| Item | Content |\n| --- | --- |\n"
    return head + "\n".join(f"| {k} | {_esc(v)} |" for k, v in rows) + "\n"


def render_markdown(root: Path = SAMPLES_DIR) -> str:
    root = Path(root)
    idx = _load(root / "scenarios_index.json")
    gt = _load(root / "tampered" / "ground_truth.json")
    out = [
        "# Ground truth for the TraceDocs sample set\n",
        "Generated by `samples/generator/ground_truth_doc.py` from the case files. Do not edit by hand; "
        "`python samples/validate.py` fails if this file is stale.\n",
        "All people, documents and amounts are fictional. Items below are *synthetic test edits* and *expected "
        "observations*; none of them is a verdict about a person. Boxes everywhere are `[x, y, w, h]`, fractions of "
        "the page, origin top-left (contract `Region`); the D1 manifest keeps `bbox` as `[x_min, y_min, x_max, y_max]` "
        "next to a contract-shaped `region`.\n",
        "## How the sets are split\n",
        "| Split | Variant | Use |\n| --- | --- | --- |\n"
        "| `samples/dev/` | a | Used while building and tuning detectors, rules and thresholds. |\n"
        "| `samples/test/` | b | Held out. A different variant of every pattern, drawn from disjoint name pools. "
        "Never used to tune thresholds; run it once to report results. |\n",
        "No person, id number, account number, source document or file content appears in both splits "
        "(`validate.py` checks all of these).\n",
        "## Cases\n",
        "| Case | Pattern | Split | Findings expected | Edited documents |\n| --- | --- | --- | --- | --- |",
    ]
    cases = []
    for c in idx["cases"]:
        d = root / c["split"] / Path(c["dir"]).name
        meta = _load(d / "case.json")
        nfind = len(_load(d / "expected_findings.json")["findings"])
        edited = ", ".join(f"`{g['doc_id']}`" for g in meta["tamper_ground_truth"]) or "none"
        out.append(f"| {c['caseId']} | {c['patternName']} | {c['split']} | {nfind} | {edited} |")
        cases.append(d)
    out.append("")
    for split in ("dev", "test"):
        out.append(f"## {split}\n")
        for d in cases:
            if d.parent.name == split:
                out.append(_case_table(d))
    out += ["## D2 single-edit samples (`samples/tampered/`, `samples/controls/`)\n",
            "| Id | Role | Type | File | Field | Expected finding | Description |\n| --- | --- | --- | --- | --- | --- | --- |"]
    for e in gt["entries"]:
        out.append(f"| {e['id']} | {e['role']} | `{e['type']}` | `{e['file']}` | {e.get('field') or '(whole page)'} | "
                   f"{'yes' if e['expected_finding'] else '**no (control)**'} | {_esc(e['description'])} |")
    out.append("")
    return "\n".join(out) + "\n"


def main() -> int:
    (SAMPLES_DIR / "ground-truth.md").write_text(render_markdown(SAMPLES_DIR), encoding="utf-8", newline="\n")
    print("wrote samples/ground-truth.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
